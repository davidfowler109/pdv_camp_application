CREATE TABLE IF NOT EXISTS camp_week (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) > 0),
  minimum_age integer NOT NULL CHECK (minimum_age BETWEEN 7 AND 18),
  maximum_age integer NOT NULL CHECK (maximum_age BETWEEN minimum_age AND 18),
  capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 250)
);

CREATE TABLE IF NOT EXISTS building (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS dorm (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  building_id integer NOT NULL REFERENCES building(id),
  name text NOT NULL CHECK (length(trim(name)) > 0),
  physical_beds integer NOT NULL CHECK (physical_beds > 0),
  UNIQUE (building_id, name)
);

CREATE TABLE IF NOT EXISTS staff_member (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  team_role text NOT NULL CHECK (team_role IN ('guide', 'equipante')),
  adult boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS weekly_dorm (
  week_id integer NOT NULL REFERENCES camp_week(id),
  dorm_id integer NOT NULL REFERENCES dorm(id),
  minimum_age integer NOT NULL CHECK (minimum_age BETWEEN 7 AND 18),
  maximum_age integer NOT NULL CHECK (maximum_age BETWEEN minimum_age AND 18),
  usable_beds integer NOT NULL CHECK (usable_beds >= 0),
  guest_beds integer NOT NULL CHECK (guest_beds BETWEEN 0 AND usable_beds),
  gender_group text NOT NULL CHECK (gender_group IN ('female', 'male')),
  in_service boolean NOT NULL,
  PRIMARY KEY (week_id, dorm_id)
);

CREATE TABLE IF NOT EXISTS weekly_dorm_staff (
  week_id integer NOT NULL,
  dorm_id integer NOT NULL,
  staff_id integer NOT NULL REFERENCES staff_member(id),
  PRIMARY KEY (week_id, dorm_id, staff_id),
  FOREIGN KEY (week_id, dorm_id) REFERENCES weekly_dorm(week_id, dorm_id)
);
